let activeLanguage: UiLanguage | null = null;

export function readUiLanguage(): UiLanguage {
  if (activeLanguage) return activeLanguage;
  const stored = readStoredLanguage();
  if (stored) return (activeLanguage = stored);
  const browserLanguage = typeof navigator === "undefined" ? "en" : navigator.language;
  return (activeLanguage = browserLanguage.toLowerCase().startsWith("de") ? "de" : "en");
}

export function setUiLanguage(language: UiLanguage): void {
  activeLanguage = language;
  try {
    globalThis.localStorage?.setItem(UI_LANGUAGE_STORAGE_KEY, language);
  } catch {
    // Storage can be disabled without blocking the language switch.
  }
  applyUiTranslations(document);
  window.dispatchEvent(
    new window.CustomEvent<UiLanguage>(UI_LANGUAGE_EVENT, { detail: language }),
  );
}

export function uiText(
  key: UiCopyKey,
  replacements: Readonly<Record<string, string | number>> = {},
): string {
  const source = readUiLanguage() === "de" ? DE[key] : EN[key];
  return Object.entries(replacements).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    source,
  );
}

export function applyUiTranslations(root: ParentNode = document): void {
  const language = readUiLanguage();
  document.documentElement.lang = language;
  root.querySelectorAll<HTMLElement>("[data-i18n]").forEach((element) => {
    element.textContent = uiText(element.dataset.i18n as UiCopyKey);
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute(
      "aria-label",
      uiText(element.dataset.i18nAriaLabel as UiCopyKey),
    );
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-title]").forEach((element) => {
    element.setAttribute("title", uiText(element.dataset.i18nTitle as UiCopyKey));
  });
  root.querySelectorAll<HTMLElement>("[data-ui-language]").forEach((element) => {
    const selected = element.dataset.uiLanguage === language;
    element.classList.toggle("is-selected", selected);
    element.setAttribute("aria-pressed", String(selected));
  });
}

export function onUiLanguageChange(listener: (language: UiLanguage) => void): () => void {
  const handler = (event: Event): void => {
    listener((event as CustomEvent<UiLanguage>).detail);
  };
  window.addEventListener(UI_LANGUAGE_EVENT, handler);
  return () => window.removeEventListener(UI_LANGUAGE_EVENT, handler);
}

function readStoredLanguage(): UiLanguage | null {
  try {
    const stored = globalThis.localStorage?.getItem(UI_LANGUAGE_STORAGE_KEY);
    return stored === "de" || stored === "en" ? stored : null;
  } catch {
    return null;
  }
}
